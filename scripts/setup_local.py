#!/usr/bin/env python3
"""Local setup implementation; invoked by setup_local.sh after dependencies install."""

import argparse
import getpass
import os
from pathlib import Path
import shlex
import subprocess
import sys

from cryptography.fernet import Fernet
from django.core.management.utils import get_random_secret_key
from dotenv import dotenv_values, load_dotenv
import psycopg2
from psycopg2 import sql

ROOT = Path(__file__).resolve().parent.parent


class SetupError(Exception):
    pass


def ask(prompt, default='', *, hidden=False, no_input=False):
    if no_input:
        return default
    try:
        value = getpass.getpass(prompt) if hidden else input(prompt)
    except EOFError as exc:
        raise SetupError('Input ended. Use --no-input for unattended setup.') from exc
    return value if value else default


def confirm(prompt, *, no_input=False):
    answer = ask(prompt + ' [Y/n]: ', 'y', no_input=no_input).lower()
    if answer not in ('y', 'yes', 'n', 'no'):
        raise SetupError('Please answer yes or no, then rerun setup.')
    return answer in ('y', 'yes')


def dotenv_quote(value):
    # python-dotenv expands ${...} even inside single quotes. Reject that input
    # rather than silently changing credentials on the next runserver invocation.
    if '${' in value:
        raise SetupError('New .env values cannot contain ${...} interpolation. Configure .env manually instead.')
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def prepare_environment(root, *, no_input=False):
    env_path = root / '.env'
    if not env_path.exists():
        values = dotenv_values(root / '.env.example')
        values.update(SECRET_KEY=get_random_secret_key(), FERNET_KEY=Fernet.generate_key().decode())
        if os.environ.get('DATABASE_URL'):
            values['DATABASE_URL'] = os.environ['DATABASE_URL']
        else:
            print('\nDatabase configuration (PostgreSQL must already be running):')
            defaults = {
                'DB_NAME': 'schoolforumdb', 'DB_USER': getpass.getuser(),
                'DB_PASSWORD': '', 'DB_HOST': 'localhost', 'DB_PORT': '5432',
            }
            for key, fallback in defaults.items():
                default = os.environ.get(key, fallback)
                hidden = key == 'DB_PASSWORD'
                prompt = 'Database password (hidden; blank keeps default): ' if hidden else f'{key} [{default}]: '
                values[key] = ask(prompt, default, hidden=hidden, no_input=no_input)
        content = '# Local development settings generated by scripts/setup_local.sh\n'
        content += ''.join(f'{key}={dotenv_quote(value)}\n' for key, value in values.items() if value is not None)
        # Exclusive creation prevents replacing an existing file; mode protects credentials.
        fd = os.open(env_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        print('Created .env with database settings and generated keys.')
    else:
        print('Using existing .env; its contents and keys are preserved.')
    # Match Django's precedence: exported variables override .env; duplicate .env
    # entries use the last value, with quoting and interpolation parsed by dotenv.
    load_dotenv(env_path)
    secret = os.environ.get('SECRET_KEY', '')
    if len(secret) < 32 or secret == 'auto-generated-by-setup-script':
        raise SetupError('SECRET_KEY must be a generated key of at least 32 characters. Check .env and exported variables; existing keys were not changed.')
    try:
        Fernet(os.environ.get('FERNET_KEY', '').encode())
    except (ValueError, TypeError) as exc:
        raise SetupError('FERNET_KEY must be a valid Fernet key. Check .env and exported variables; existing keys were not changed.') from exc


def prepare_database(connection, *, no_input=False):
    if connection.vendor != 'postgresql':
        raise SetupError('WolfKey requires PostgreSQL (including the pg_trgm extension).')
    params = connection.get_connection_params()
    params.setdefault('connect_timeout', 5)
    # First try the actual database; existing databases need no maintenance-DB access.
    try:
        target = psycopg2.connect(**params)
    except psycopg2.OperationalError:
        maintenance = dict(params, dbname='postgres')
        try:
            admin = psycopg2.connect(**maintenance)
            try:
                admin.autocommit = True
                with admin.cursor() as cursor:
                    cursor.execute('SELECT 1 FROM pg_database WHERE datname = %s', (params['dbname'],))
                    if cursor.fetchone():
                        raise SetupError('The configured database exists but cannot be connected to. Check its connection permissions.')
                    if not confirm(f"Create PostgreSQL database {params['dbname']!r} using the configured connection?", no_input=no_input):
                        raise SetupError('Database creation skipped. Create the configured database, then rerun setup.')
                    cursor.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(params['dbname'])))
            finally:
                admin.close()
        except psycopg2.Error as exc:
            # Connection error messages may echo credentials from a URL; don't print them.
            raise SetupError('Cannot create/connect to PostgreSQL. Check DB_* / DATABASE_URL, start the server, and ensure the configured role exists and has CREATEDB permission. On macOS: brew install postgresql@15 && brew services start postgresql@15; on Linux install PostgreSQL and start its service.') from exc
        target = psycopg2.connect(**params)
        print('Created the configured database.')
    try:
        with target:
            with target.cursor() as cursor:
                cursor.execute("SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm'")
                if not cursor.fetchone():
                    cursor.execute('CREATE EXTENSION IF NOT EXISTS pg_trgm')
    except psycopg2.Error as exc:
        raise SetupError('Cannot enable pg_trgm. Install PostgreSQL contrib extensions and ask the database owner to enable pg_trgm, then rerun.') from exc
    finally:
        target.close()
    print('PostgreSQL connection and pg_trgm verified.')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--no-input', action='store_true')
    parser.add_argument('--skip-superuser', action='store_true')
    args = parser.parse_args(argv)
    os.chdir(ROOT)
    prepare_environment(ROOT, no_input=args.no_input)
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'student_forum.settings')
    import django
    django.setup()
    from django.db import connections
    prepare_database(connections['default'], no_input=args.no_input)
    subprocess.run([sys.executable, 'manage.py', 'migrate', '--noinput'], check=True)
    subprocess.run([sys.executable, 'manage.py', 'check'], check=True)
    if not args.no_input and not args.skip_superuser and confirm('Create Django superuser now?'):
        subprocess.run([sys.executable, 'manage.py', 'createsuperuser'], check=True)
    print('\nSetup finished. Run the development server with:')
    print(f'  {shlex.quote(sys.executable)} {shlex.quote(str(ROOT / "manage.py"))} runserver')


if __name__ == '__main__':
    try:
        main()
    except (SetupError, psycopg2.Error) as exc:
        message = str(exc) if isinstance(exc, SetupError) else 'PostgreSQL connection failed. Check your database configuration and server.'
        print(f'\nSetup failed: {message}', file=sys.stderr)
        sys.exit(1)
    except subprocess.CalledProcessError as exc:
        print(f'\nSetup failed: {exc.cmd[2]} exited with status {exc.returncode}. Fix the error above, then rerun.', file=sys.stderr)
        sys.exit(exc.returncode)
    except KeyboardInterrupt:
        print('\nSetup cancelled; rerun when ready.', file=sys.stderr)
        sys.exit(130)
